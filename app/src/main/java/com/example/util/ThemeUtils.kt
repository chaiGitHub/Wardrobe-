package com.example.util

import androidx.compose.ui.graphics.Color
import kotlin.math.abs

data class BadgeStyle(
    val backgroundColor: Color,
    val textColor: Color,
    val borderColor: Color
)

object ThemeUtils {

    /**
     * Resolves dynamic tag chip styling (background, text, and border) consistently by text hash.
     */
    fun getTagBadgeStyle(tag: String): BadgeStyle {
        val cleanTag = tag.trim().removePrefix("#").lowercase()

        // Specific semantic tags
        return when {
            cleanTag.contains("wash") || cleanTag.contains("laundry") -> BadgeStyle(
                backgroundColor = Color(0xFFFEF2F2),
                textColor = Color(0xFFB91C1C),
                borderColor = Color(0xFFFECACA)
            )
            cleanTag.contains("beautiful") || cleanTag.contains("favorite") -> BadgeStyle(
                backgroundColor = Color(0xFFFAF5FF),
                textColor = Color(0xFF7E22CE),
                borderColor = Color(0xFFE9D5FF)
            )
            cleanTag.contains("chiffon") || cleanTag.contains("silk") -> BadgeStyle(
                backgroundColor = Color(0xFFFDF2F8),
                textColor = Color(0xFFBE185D),
                borderColor = Color(0xFFFBCFE8)
            )
            cleanTag.contains("hot") || cleanTag.contains("summer") -> BadgeStyle(
                backgroundColor = Color(0xFFFFFBEB),
                textColor = Color(0xFFB45309),
                borderColor = Color(0xFFFDE68A)
            )
            cleanTag.contains("cool") || cleanTag.contains("breathable") -> BadgeStyle(
                backgroundColor = Color(0xFFF0FDF4),
                textColor = Color(0xFF15803D),
                borderColor = Color(0xFFBBF7D0)
            )
            cleanTag.contains("work") || cleanTag.contains("formal") -> BadgeStyle(
                backgroundColor = Color(0xFFEEF2FF),
                textColor = Color(0xFF4338CA),
                borderColor = Color(0xFFC7D2FE)
            )
            else -> {
                // Generated by hash
                val styles = listOf(
                    BadgeStyle(Color(0xFFEDE9FE), Color(0xFF6D28D9), Color(0xFFDDD6FE)),
                    BadgeStyle(Color(0xFFE0E7FF), Color(0xFF4338CA), Color(0xFFC7D2FE)),
                    BadgeStyle(Color(0xFFDBEAFE), Color(0xFF1D4ED8), Color(0xFFBFDBFE)),
                    BadgeStyle(Color(0xFFE0F2FE), Color(0xFF0369A1), Color(0xFFBAE6FD)),
                    BadgeStyle(Color(0xFFCCFBF1), Color(0xFF0F766E), Color(0xFF99F6E4)),
                    BadgeStyle(Color(0xFFD1FAE5), Color(0xFF047857), Color(0xFFA7F3D0)),
                    BadgeStyle(Color(0xFFFEF3C7), Color(0xFFB45309), Color(0xFFFDE68A)),
                    BadgeStyle(Color(0xFFFFEDD5), Color(0xFFC2410C), Color(0xFFFED7AA))
                )
                val hash = abs(cleanTag.hashCode())
                styles[hash % styles.size]
            }
        }
    }

    /**
     * Resolves laundry status badge style ("need wash", "washed", "clean").
     */
    fun getWashStatusStyle(status: String): BadgeStyle {
        return when (status.trim().lowercase()) {
            "need wash", "unwashed", "dirty" -> BadgeStyle(
                backgroundColor = Color(0xFFFEF2F2),
                textColor = Color(0xFFDC2626),
                borderColor = Color(0xFFFCA5A5)
            )
            "washed", "washing", "laundry done" -> BadgeStyle(
                backgroundColor = Color(0xFFECFDF5),
                textColor = Color(0xFF059669),
                borderColor = Color(0xFFA7F3D0)
            )
            "clean", "ready" -> BadgeStyle(
                backgroundColor = Color(0xFFF0F9FF),
                textColor = Color(0xFF0284C7),
                borderColor = Color(0xFFBAE6FD)
            )
            else -> BadgeStyle(
                backgroundColor = Color(0xFFF1F5F9),
                textColor = Color(0xFF475569),
                borderColor = Color(0xFFE2E8F0)
            )
        }
    }

    /**
     * Rating color for Cost-Per-Wear (CPW).
     */
    fun getCpwBadgeStyle(cpw: Double): BadgeStyle {
        return when {
            cpw <= 5.0 -> BadgeStyle(
                backgroundColor = Color(0xFFECFDF5), // Emerald
                textColor = Color(0xFF047857),
                borderColor = Color(0xFFA7F3D0)
            )
            cpw <= 15.0 -> BadgeStyle(
                backgroundColor = Color(0xFFF0FDFA), // Teal
                textColor = Color(0xFF0F766E),
                borderColor = Color(0xFF99F6E4)
            )
            cpw <= 35.0 -> BadgeStyle(
                backgroundColor = Color(0xFFFFFBEB), // Amber
                textColor = Color(0xFFB45309),
                borderColor = Color(0xFFFDE68A)
            )
            else -> BadgeStyle(
                backgroundColor = Color(0xFFF8FAFC), // Slate
                textColor = Color(0xFF64748B),
                borderColor = Color(0xFFE2E8F0)
            )
        }
    }

    /**
     * Category badge color (Dress, Pant, Tshirt, Bra, etc.)
     */
    fun getCategoryStyle(category: String): BadgeStyle {
        return when (category.trim().lowercase()) {
            "dress" -> BadgeStyle(Color(0xFFFAF5FF), Color(0xFF7E22CE), Color(0xFFE9D5FF))
            "pant", "pants" -> BadgeStyle(Color(0xFFEFF6FF), Color(0xFF1D4ED8), Color(0xFFBFDBFE))
            "tshirt", "t-shirt", "top" -> BadgeStyle(Color(0xFFF0FDFA), Color(0xFF0F766E), Color(0xFF99F6E4))
            "bra", "underwear" -> BadgeStyle(Color(0xFFFFF1F2), Color(0xFFE11D48), Color(0xFFFECDD3))
            "skirt" -> BadgeStyle(Color(0xFFFDF2F8), Color(0xFFBE185D), Color(0xFFFBCFE8))
            else -> BadgeStyle(Color(0xFFF1F5F9), Color(0xFF475569), Color(0xFFE2E8F0))
        }
    }

    private const val FONT_PREFS_NAME = "wardrobe_font_prefs"
    private const val KEY_FONT_SCALE = "user_font_scale"

    fun getSavedFontScale(context: android.content.Context): Float {
        return context.getSharedPreferences(FONT_PREFS_NAME, android.content.Context.MODE_PRIVATE)
            .getFloat(KEY_FONT_SCALE, 1.0f)
    }

    fun saveFontScale(context: android.content.Context, scale: Float) {
        context.getSharedPreferences(FONT_PREFS_NAME, android.content.Context.MODE_PRIVATE)
            .edit()
            .putFloat(KEY_FONT_SCALE, scale)
            .apply()
    }
}
